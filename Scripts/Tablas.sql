CREATE TABLE [Clientes] (
	[Id] INTEGER NOT NULL IDENTITY,
	[Nombre] NVARCHAR(150) NOT NULL,
	[Email] NVARCHAR(150) NOT NULL UNIQUE,
	[Telefono] NVARCHAR(30),
	[Direccion] NVARCHAR(255),
	[FechaAlta] DATETIME2 NOT NULL DEFAULT GETDATE(),
	[Activo] BIT NOT NULL DEFAULT 1,
	PRIMARY KEY([Id])
);
GO

CREATE TABLE [Productos] (
	[Id] INTEGER NOT NULL IDENTITY,
	[Sku] NVARCHAR(255) NOT NULL UNIQUE,
	[Nombre] NVARCHAR(255) NOT NULL,
	[Descripcion] NVARCHAR(255),
	[Precio] DECIMAL(10, 2) NOT NULL,
	[Stock] INTEGER NOT NULL DEFAULT 0,
	[Activo] BIT NOT NULL DEFAULT 1,
	[FechaCreacion] DATETIME2 NOT NULL DEFAULT GETDATE(),
	PRIMARY KEY([Id])
);
GO

CREATE TABLE [Proveedores] (
	[Id] INTEGER NOT NULL IDENTITY,
	[NombreEmpresa] NVARCHAR(150) NOT NULL UNIQUE,
	[Contacto] NVARCHAR(255),
	[Email] NVARCHAR(150),
	[Telefono] NVARCHAR(255),
	[Activo] BIT NOT NULL DEFAULT 1,
	[FechaAlta] DATETIME2 NOT NULL DEFAULT GETDATE(),
	PRIMARY KEY([Id])
);
GO

CREATE TABLE [ProductosProveedores] (
	[ProductoId] INTEGER NOT NULL,
	[ProveedorId] INTEGER NOT NULL,
	[PrecioCompra] DECIMAL(10, 2) NOT NULL,
	[FechaAsociacion] DATETIME2 NOT NULL DEFAULT GETDATE(),
	PRIMARY KEY([ProductoId], [ProveedorId])
);
GO


ALTER TABLE [ProductosProveedores]
ADD FOREIGN KEY([ProductoId])
REFERENCES [Productos]([Id])
ON UPDATE NO ACTION ON DELETE NO ACTION;
GO
ALTER TABLE [ProductosProveedores]
ADD FOREIGN KEY([ProveedorId])
REFERENCES [Proveedores]([Id])
ON UPDATE NO ACTION ON DELETE NO ACTION;
GO